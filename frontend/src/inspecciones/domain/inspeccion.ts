export type EstadoFoto = 'pendiente' | 'en_proceso' | 'completada' | 'error'

export type Severidad = 'critical' | 'high' | 'medium' | 'low'

export interface SeccionCasco {
  id: number
  codigo: string
  nombre: string
  descripcion: string
  orden: number
}

/** Class kind in the vision taxonomy: a hull part or a defect. */
export type TipoClase = 'anomalia' | 'componente'

/** One entry per detected class, as aggregated by the vision worker. */
export interface Deteccion {
  clase: string
  /** Spanish label from the taxonomy (the readable class name when the taxonomy does not know it). */
  etiqueta: string
  /** null when the taxonomy does not know the class. */
  tipo: TipoClase | null
  /** Anomalies only. */
  severidad: Severidad | null
  cantidad: number
  confianzaMaxima: number
}

export interface Foto {
  id: number
  seccion: SeccionCasco
  imagenOriginal: string | null
  imagenAnotada: string | null
  detecciones: Deteccion[]
  tiempoInferenciaMs: number | null
  severidad: Severidad | null
  estado: EstadoFoto
  errorDetalle: string | null
  /** Catalog id of the model that analyzed (or will analyze) the photo; null when none was chosen yet. */
  modelo: string | null
  modeloVersion: string | null
  taxonomiaVersion: string | null
  /** The server keeps the boxes and masks of the last analysis (see `obtenerDetecciones`). */
  detalleDisponible: boolean
  fechaCreacion: string
}

/** A user as other records reference it (leader, uploader). */
export interface UsuarioRef {
  id: number
  nombre: string
}

/** What the logged-in user may do on one inspection, as the server computed it. */
export interface PermisosInspeccion {
  ver: boolean
  /** The leader (or an admin): may delete it, change its privacy and manage its members. */
  esLider: boolean
  subirFotos: boolean
  analizar: boolean
  editarReporte: boolean
  editarInspeccion: boolean
}

export interface Inspeccion {
  id: number
  buqueId: number
  buqueNombre: string
  /** Given by the user or generated by the backend, so it is never blank. */
  nombre: string
  /** Most severe level among the analyzed photos; null until one is processed. */
  severidadMax: Severidad | null
  descripcion: string
  tomadoPor: string
  fechaCreacion: string
  fechaModificacion: string
  totalFotos: number
  /** The creator, who manages the inspection; null for inspections created before accounts existed. */
  lider: UsuarioRef | null
  /** Private inspections are visible only to their leader and members. */
  privada: boolean
}

export interface InspeccionDetalle extends Inspeccion {
  fotos: Foto[]
  misPermisos: PermisosInspeccion
}

export interface NuevaInspeccion {
  buqueId: number
  /** Optional: when blank the backend generates one. */
  nombre?: string
  tomadoPor: string
  descripcion: string
}

/** Server-side search criteria; every field is optional and they combine with AND. */
export interface FiltroInspecciones {
  buqueId?: number
  /** First day to include, `YYYY-MM-DD`. */
  desde?: string
  /** Last day to include, `YYYY-MM-DD`. */
  hasta?: string
  /** Keeps inspections whose maximum severity is at least this level. */
  severidadMin?: Severidad
  /** Text contained in the inspection name (the backend requires 2-100 characters). */
  q?: string
}

/** One page of a search; `siguiente` is the opaque cursor to request the next one. */
export interface PaginaInspecciones {
  resultados: Inspeccion[]
  siguiente: string | null
  hayMas: boolean
}

/** Partial photo state pushed by the server while a photo is analyzed. */
export interface ActualizacionFoto {
  fotoId: number
  estado: EstadoFoto
  severidad: Severidad | null
  detecciones: Deteccion[]
  tiempoInferenciaMs: number | null
  imagenAnotada: string | null
  errorDetalle: string | null
  modelo: string | null
  modeloVersion: string | null
  taxonomiaVersion: string | null
  detalleDisponible: boolean
}

export type EventoInspeccion =
  | { tipo: 'foto-creada'; foto: Foto }
  | { tipo: 'foto-actualizada'; actualizacion: ActualizacionFoto }
  | { tipo: 'foto-eliminada'; fotoId: number }
